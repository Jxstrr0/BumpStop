export type StringKey = keyof typeof STRINGS

export function t(key: StringKey): string {
  return STRINGS[key]
}

/** A string with {name} gaps filled in: tf('report.laps', { n: '2' }). */
export function tf(key: StringKey, vars: Record<string, string>): string {
  const text = STRINGS[key].replace(/\{(\w+)\}/g, (all, name: string) => vars[name] ?? all)
  // Money ends in "cr.", so a sentence that ends on an amount would show "cr.." (Kelbo's playtest): keep one full stop.
  return text.replace(/cr\.\./g, 'cr.')
}
