/** A string with {name} gaps filled in: tf('sim.peak', { temp: '96', at: '7.2' }). */
export function tf(key: StringKey, vars: Record<string, string>): string {
  return STRINGS[key].replace(/\{(\w+)\}/g, (all, name: string) => vars[name] ?? all)
}
